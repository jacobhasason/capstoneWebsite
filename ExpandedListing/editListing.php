function getListingTitleByID($listingID, $projectUrl, $key) {
    $url = $projectUrl .
            "/rest/v1/Listing?select=title&listingID=eq." .
            urlencode($listingID) .
            "&limit=1";

    $ch = curl_init($url);

    curl_setopt_array($ch, [
        CURLOPT_HTTPHEADER => [
            "apikey: $key",
            "Authorization: Bearer $key"
        ],
        CURLOPT_RETURNTRANSFER => true
    ]);

    $response = curl_exec($ch);
    curl_close($ch);

    $rows = json_decode($response, true);

    return $rows[0]['title'] ?? "Related Listing #" . $listingID;
}

function insertRelatedListing(
        $projectUrl,
        $key,
        $listingID,
        $topic,
        $title,
        $type,
        $file = null,
        $link = null
) {
    $insertUrl = $projectUrl . "/rest/v1/RelatedListing";

    $postData = [
        "listingID" => (int) $listingID,
        "topic" => $topic,
        "title" => $title,
        "type" => $type,
        "file" => $file,
        "links" => $link
    ];

    $ch = curl_init($insertUrl);

    curl_setopt_array($ch, [
        CURLOPT_HTTPHEADER => [
            "apikey: $key",
            "Authorization: Bearer $key",
            "Content-Type: application/json"
        ],
        CURLOPT_POST => true,
        CURLOPT_POSTFIELDS => json_encode($postData),
        CURLOPT_RETURNTRANSFER => true
    ]);

    curl_exec($ch);
    curl_close($ch);
}
