<script>
                    // Explicitly expose functions to the global window scope 
                    // so the HTML inline onclick attribute can actually see them, and prevent yeeting the COMPUTA
                    window.removeRelated = async function (btn, relatedListingID) {
                        const response = await fetch(
                                `controller.php?page=removeRelatedListing&relatedListingID=${relatedListingID}`
                                );

                        const text = await response.text();
                        console.log(text);

                        btn.closest(".related-listing").remove();
                    };

                    window.addRelatedListing = function () {
                        const container = document.getElementById("relatedListingList");
                        const div = document.createElement("div");
                        div.className = "related-listing";
                        div.innerHTML = `
            <label>Related Listing:</label>
            <select name="relatedListingIDs[]" class="related-listing-select">
                <option value="">Select Related Listing</option>
            </select>
            <button type="button" onclick="removeRelated(this)">✕</button>
        `;
                        container.appendChild(div);

                        syncTopics();
                    };

                    /* Synchronizes checked values into the hidden input payload */
                    function syncTopics() {
                        const checkedTopics = [
                            ...document.querySelectorAll(".real-topic:checked")
                        ].map(cb => cb.value);

                        const hiddenInput = document.getElementById("topicHidden");
                        if (hiddenInput) {
                            hiddenInput.value = JSON.stringify(checkedTopics);
                        }

                        if (typeof updateRelatedListings === "function") {
                            updateRelatedListings();
                        }
                    }

                    document.addEventListener("change", function (e) {
                        /* CATEGORY CLICKED */
                        if (e.target.classList.contains("category-box")) {
                            const categoryBox = e.target;
                            let children = [];
                            try {
                                children = JSON.parse(categoryBox.dataset.children || "[]");
                            } catch (err) {
                                return;
                            }

                            const isChecked = categoryBox.checked;
                            children.forEach(id => {
                                const child = document.querySelector(`.real-topic[value="${id}"]`);
                                if (child) {
                                    child.checked = isChecked;
                                }
                            });
                            syncTopics();
                            return;
                        }

                        /* INDIVIDUAL TOPIC CHANGES */
                        if (e.target.classList.contains("real-topic")) {
                            const topic = e.target;
                            const wrapper = topic.closest(".topic-category");
                            if (!wrapper)
                                return;

                            const categoryBox = wrapper.querySelector(".category-box");
                            const children = wrapper.querySelectorAll(".real-topic");
                            const checked = wrapper.querySelectorAll(".real-topic:checked");

                            if (categoryBox) {
                                categoryBox.checked = (children.length === checked.length);
                            }
                            syncTopics();
                        }
                    });

                    window.addEventListener("DOMContentLoaded", () => {
                        syncTopics();
                    });
</script>
