        <h1>About</h1>

        <p>
            AI/LM integration with visualization is presented in the form
            of an emerging Visual Knowledge Discovery ecosystem that is a
            set of interconnected algorithms, software projects, and
            platforms that co-evolve around a shared VKD technological base.
            Interpretable ML algorithms and lossless visualization of
            high-dimensional data are the core of VKD, allowing end users
            to discover trustworthy models.
        </p>
        <br>
        <p>
            The search on this site allows you to find specific AI/VKD sources
            (papers, presentations, software) from the Visual Knowledge Discovery Lab
            at Central Washington University. Several publications are linked to
            their respective software at
            <a href="https://github.com/CWU-VKD-LAB" target="_blank" rel="noopener noreferrer">
                CWU-VKD-LAB
            </a>,
            allowing experiments with the software.
        </p>

